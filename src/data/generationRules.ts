import type { LabId } from './labs';

/**
 * Правила Поколений (ADR-0013): один поворот правил на Поколение, заданный вручную, без
 * случайности. Таблица — только содержимое и числа; считает их `src/economy/rules.ts`.
 *
 * «Рассвет» — обучающее Поколение и Правила не имеет. Остальные Правила приходят следующими
 * тикетами плана (`docs/plans/deepening.md`, слой 3): таблица растёт строками, а движок читает
 * её вид через `effect.kind`.
 *
 * Правило ни при каких числах не трогает базовые цену и Доход Модели в каталоге: оно множит
 * то, что игрок платит и получает, одинаково для всех Моделей Поколения, поэтому лестница
 * Ранга и полоса окупаемости 3× (ADR-0001) остаются как есть. Держит это тест над каталогом.
 */
export type RuleEffect =
  /**
   * Цена всех Моделей падает со временем Забега: множитель `floor + (1 − floor) · 0,5^(минуты / halfLifeMin)`.
   * Минуты целые, поэтому цена на экране меняется раз в минуту, а не двадцать раз в секунду.
   */
  | { kind: 'priceDecay'; floor: number; halfLifeMin: number }
  /** Доход всех Моделей растёт на `perLab` за каждую Лабораторию в офисе сверх первой. */
  | { kind: 'labVariety'; perLab: number }
  /**
   * Запросы идут `top` умнейшим Моделям Поколения (старшие Ранги), остальные платят долю `rest`
   * от Дохода. Рейтинг берётся по Рангу каталога, а не по составу офиса: покупка новой Модели
   * не отнимает Доход у уже нанятых, и прирост на карточке магазина остаётся неотрицательным.
   */
  | { kind: 'topRouter'; top: number; rest: number }
  /**
   * Лидер Арены — одна Лаборатория Поколения; каждые `periodMin` минут Забега его место занимает
   * другая. Модели лидера приносят в `bonus` раз больше Дохода. За `warnSec` секунд до смены
   * лента и HUD называют следующего лидера. Порядок лидеров выводится из времени Забега и его
   * начала, поэтому в сохранение ничего не пишется. Минутный эффект: в Оффлайн-доход не входит.
   */
  | { kind: 'arenaLeader'; periodMin: number; warnSec: number; bonus: number }
  /**
   * Очередь закупок: до `capacity` Агентов ставятся в очередь и нанимаются сами, по порядку, по
   * цене ручной покупки, как только хватает Токенов. Исполняется только в живом тике: пока игры
   * нет, очередь стоит, как Температура и События, а Оффлайн-доход идёт по общему потолку.
   */
  | { kind: 'purchaseQueue'; capacity: number }
  /**
   * Дефицит: каждый нанятый Агент подряд удорожает следующие покупки на `perAgent`, пока ряд не
   * упрётся в `maxExtra` (цена не выше `1 + maxExtra`). Ряд обрывается, если `resetSec` секунд
   * игровых часов не было ни одной покупки: пауза возвращает цену. Множитель общий для всех Моделей.
   */
  | { kind: 'buyStreak'; perAgent: number; maxExtra: number; resetSec: number }
  /**
   * «Подумай ещё»: удержание Клика (Пробел, Enter или палец на кнопке) не платит по Клику, а копит
   * размышление — до `maxSec` секунд, по `clicksPerSec` Кликов в секунду. Размышление платится одним
   * ударом, когда удержание оборвалось дольше чем на `releaseSec`, или на пределе, и тем больше,
   * чем дольше копилось: множитель `1 + bonusPerSec · секунды`. Живёт только в активной игре.
   */
  | { kind: 'heldThought'; clicksPerSec: number; bonusPerSec: number; maxSec: number; releaseSec: number };

export interface GenerationRule {
  id: 'scarcity' | 'variety' | 'price-war' | 'think' | 'agents' | 'router' | 'arena';
  /** Индекс Поколения, как в `CATALOG` и `GameState.generation`. */
  generation: number;
  name: string;
  /** Одна строка для HUD и подсказки: что Правило делает. */
  summary: string;
  effect: RuleEffect;
  /** Заголовок Новостной ленты, который объявляет Правило на входе в Поколение. */
  news: string;
  /** Реплика Модели на входе в Поколение; в «Переписку» не пишется и Достижений не двигает. */
  quip: { lab: LabId; text: string };
}

