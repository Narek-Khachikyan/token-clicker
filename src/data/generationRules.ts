import type { LabId } from './labs';

/**
 * Правила Поколений (ADR-0013): один поворот правил на Поколение, заданный вручную, без
 * случайности. Таблица — только содержимое и числа; считает их `src/economy/rules.ts`.
 *
 * «Рассвет» — обучающее Поколение и Правила не имеет. Остальные Правила приходят следующими
 * тикетами плана (`docs/plans/deepening.md`, слой 3): таблица растёт строками, а движок читает
 * её вид через `effect.kind`.
 *
 * Правило ни при каких числах не трогает базовые цену и Доход Модели в каталоге: оно множит
 * то, что игрок платит и получает, одинаково для всех Моделей Поколения, поэтому лестница
 * Ранга и полоса окупаемости 3× (ADR-0001) остаются как есть. Держит это тест над каталогом.
 */
export type RuleEffect =
  /**
   * Цена всех Моделей падает со временем Забега: множитель `floor + (1 − floor) · 0,5^(минуты / halfLifeMin)`.
   * Минуты целые, поэтому цена на экране меняется раз в минуту, а не двадцать раз в секунду.
   */
  | { kind: 'priceDecay'; floor: number; halfLifeMin: number }
  /** Доход всех Моделей растёт на `perLab` за каждую Лабораторию в офисе сверх первой. */
  | { kind: 'labVariety'; perLab: number };

export interface GenerationRule {
  id: 'variety' | 'price-war';
  /** Индекс Поколения, как в `CATALOG` и `GameState.generation`. */
  generation: number;
  name: string;
  /** Одна строка для HUD и подсказки: что Правило делает. */
  summary: string;
  effect: RuleEffect;
  /** Заголовок Новостной ленты, который объявляет Правило на входе в Поколение. */
  news: string;
  /** Реплика Модели на входе в Поколение; в «Переписку» не пишется и Достижений не двигает. */
  quip: { lab: LabId; text: string };
}

