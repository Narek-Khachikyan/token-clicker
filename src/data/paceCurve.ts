/**
 * Целевая кривая темпа кампании (план `docs/plans/deepening.md`, слой 0).
 *
 * Одна таблица для всех, кто меряет темп: `tools/sim.ts` печатает против неё время каждого
 * Поколения, а дешёвая проверка в `npm test` читает отсюда же. Числа живут здесь, а не в коде
 * симулятора, чтобы правка кривой была правкой данных.
 *
 * `minutes` — сколько игровых минут жадная политика проводит в Поколении: от входа в него до
 * Престижа (у последнего — до покупки Флагмана, то есть до Финала контента). Первый Престиж
 * должен лечь в окно 30–45 минут, дальше Поколения растут к ~120 минутам, всего около 10 часов.
 * Выбрано без смещения вверх: 38 — середина окна первого Престижа, остальное — ровный рост
 * 45 → 120, дающий 608 минут. Подгонка баланса под кривую — задача следующих слоёв, не этой таблицы.
 */
export interface PaceTarget {
  /** Индекс Поколения, как в `CATALOG` и `GameState.generation`. */
  generation: number;
  minutes: number;
}

export const PACE_CURVE: readonly PaceTarget[] = [
  { generation: 0, minutes: 38 },
  { generation: 1, minutes: 45 },
  { generation: 2, minutes: 55 },
  { generation: 3, minutes: 65 },
  { generation: 4, minutes: 80 },
  { generation: 5, minutes: 95 },
  { generation: 6, minutes: 110 },
  { generation: 7, minutes: 120 },
];

/**
 * Допуск симулятора на каждое Поколение: доля от `minutes`, в которую должно лечь время жадной
 * политики. Одно число на все Поколения: кривая задаёт ритм, а не точность до минуты, и
 * симулятор честно колеблется от зерна Событий и порядка покупок.
 *
 * Замер `tools/sim.ts --campaign` на делителе Престижа 4,5e11 (зерна 1, 2, 3, 7 дают те же цифры
 * в пределах минуты), минуты факт / кривая: 31,6/38, 67,3/45, 64,1/55, 100,9/65, 171,8/80,
 * 114,4/95, 42,1/110, 16,2/120; всего 608,5 из 608. С деревом Перков (ADR-0012, жадная политика берёт самый дорогой доступный Перк) тот же замер: 31,6/38, 67,3/45, 63,5/55, 89,4/65, 146,4/80, 92,9/95, 29,6/110, 11,3/120; всего 531,9. В допуск ±25% ложатся Поколения 1, 3 и 6.
 * С Правилами Мультимодальной («Разнообразие», +3% за Лабораторию) и Omni («Ценовая война», дно 0,5, полупериод
 * 15 минут) Поколения 3 и 4 берутся за 52,3 и 81,0 минуты вместо 63,5 и 89,4, всего 512,3.
 * С Характерами всех восьми Лабораторий (ADR-0011, #106) тот же замер: 31,1/38, 64,9/45, 43,4/55, 73,3/65, 131,5/80, 82,8/95, 36,1/110, 9,7/120; всего 472,8 против 519,2 без них (`--no-characters`).
 * С Правилами 1–5 (до Агентной) и без Курсов (`--course none`, #111) замер на тех же ручках: 31,1/38, 69,3/45, 43,1/55, 73,3/65, 131,5/80, 82,8/95, 36,1/110, 9,5/120; всего 476,8.
 * Курс (ADR-0013, слой 4) сдвигает кампанию на проценты, а не на часы: `--course` с Курсом «Бережливость» 447,7, «Масштабирование» 436,7, «Ручная работа» 424,0; на случайных предложениях (`--course first`) 477,1, Курсы выпали «Холодная голова», «Дефицит GPU» (Правило), «Охота за сигналом»… Полный замер по Курсам — в ADR-0013, «Слой 4».
 * С кривыми порогов Апгрейдов Модели по Рангу (#119, доли 0,9–1,1) замер с теми же ручками и `--course none` не меняется: 476,8 минуты и до них, и с ними, потому что жадная политика упирается в цену ступеней, а не в пороги.
 * Остальные не ложатся, и ручками темпа (делитель, форма потолка Compute) их не подвинуть:
 * последнее Поколение заканчивается покупкой Флагмана, то есть лестницей Ранга (ADR-0001), а не
 * Престижем, и берётся за ~16 минут при любых ручках; а форма шагов 2, 4, 5 задана каталогом
 * (размер ростера и множители Перков), поэтому делитель сдвигает кампанию целиком, не по одному
 * Поколению. Подгонку по Поколениям делают слои с Правилами Поколений (план, слой 3).
 */
export const PACE_TOLERANCE = 0.25;

/** Окно, в которое должен лечь первый Престиж, в минутах от начала игры. */
export const FIRST_PRESTIGE_WINDOW_MIN = { from: 30, to: 45 } as const;

/** Минут от начала кампании до Финала контента по кривой. */
export function paceTotalMinutes(): number {
  return PACE_CURVE.reduce((sum, p) => sum + p.minutes, 0);
}
