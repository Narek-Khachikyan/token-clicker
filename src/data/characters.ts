/**
 * Характер Лаборатории (ADR-0011): таблица свойств по репутации, а не данные Artificial Analysis.
 *
 * Только данные: как Характер зависит от состава офиса, считает `economy/character.ts`.
 * Эффект — вид и коэффициент на единицу силы (доли Агентов Лаборатории) либо на единицу
 * разнообразия (другие Лаборатории и Модели в офисе), поэтому Лаборатория, ушедшая на треть из
 * офиса, ослабляет свой Характер на треть, а не выключает его. Действовать Характер может на
 * Температуру, Галлюцинации, Синергию, Клик и События, но НИКОГДА на базовые цену и Доход
 * Модели: Ранги разных Лабораторий перемежаются, и скидка DeepSeek поставила бы Ранг 5 ниже
 * чужого Ранга 4 (`AGENTS.md`, правило 3). Поэтому в объединении ниже нет вида, который касается
 * `baseCost` или `baseIncome`, и новый вид без этого условия не добавляется.
 */
export type CharacterEffect =
  /** Скорость перегрева × (1 + perStrength × сила): минус — перегрев копится медленнее. */
  | { kind: 'heat'; perStrength: number }
  /** Прибавка к силе жара: сила × perStrength поверх `TEMP_YIELD_MAX`, минус — жар даёт меньше. */
  | { kind: 'yield'; perStrength: number }
  /**
   * Прибавка лабораторной Синергии Лаборатории растёт в (1 + perLab × число других Лабораторий в
   * офисе) раз. Считается не от силы, а от разнообразия: чистый офис Google её не получает.
   */
  | { kind: 'ecosystem'; perLab: number }
  /** Клик × (1 + perStrength × сила): весь Клик, кроме возврата «Ночного кодинга». */
  | { kind: 'click'; perStrength: number }
  /** Частота Галлюцинаций × (1 + perStrength × сила). */
  | { kind: 'hallu'; perStrength: number }
  /**
   * Вес Волны хайпа в розыгрыше вида События × (1 + perStrength × сила). Меняет только частоту:
   * размер Волны, её длительность и условие «платит пойманный Золотой Токен» остаются прежними.
   */
  | { kind: 'hype'; perStrength: number }
  /**
   * Доход каждой чужой Модели × (1 + max × n / (n + halfAgents)), где n — Агенты Лаборатории в
   * офисе: сама Лаборатория не усиливается. Зависит от числа её Агентов, а не от их доли: доля
   * падала бы от покупки чужого Агента, и покупка могла бы уменьшить Доход (магазин обещает, что
   * прирост от Агента не бывает отрицательным).
   */
  | { kind: 'openWeights'; max: number; halfAgents: number }
  /** Доход Моделей Лаборатории × (1 + perModel × число других Моделей офиса с достаточным числом Агентов). */
  | { kind: 'pipeline'; perModel: number };

export interface Character {
  /** Название свойства: так оно стоит в магазине и в реплике Маскота. */
  name: string;
  /** Что оно делает, одной фразой: печатается в магазине ДО найма. */
  summary: string;
  effects: readonly CharacterEffect[];
}

