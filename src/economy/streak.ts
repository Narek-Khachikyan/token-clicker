/**
 * Серия: быстрые Клики подряд, сложенные в уровень отклика.
 *
 * Уровень меняет только то, что игрок видит и слышит (высоту звука, число искр, ступень `+N`).
 * Стоимость Клика он не трогает: `clickValue` про Серию не знает, и это сторожит тест стора.
 * Функции чистые и живут здесь, а не в сторе: момент Клика приходит аргументом, часов тут нет.
 */

/** Окно, в котором Клики считаются одной Серией, мс. Дольше — игрок успевает «остыть» между нажатиями. */
export const STREAK_WINDOW_MS = 1500;

/** Высший уровень Серии; уровни идут 0…STREAK_MAX_LEVEL. */
export const STREAK_MAX_LEVEL = 4;

/**
 * Сколько Кликов в окне нужно, чтобы выйти на уровень (индекс = уровень).
 *
 * 3 за 1,5 с — это два Клика в секунду, обычный ритм; 11 за 1,5 с — около семи в секунду, быстрый
 * человек. Удержание клавиши (10 в секунду, 15 в окне) стоит на высшем уровне с запасом.
 */
export const STREAK_STEPS: readonly number[] = [0, 3, 5, 8, 11];

/** Сколько моментов хранить: больше, чем нужно высшему уровню, но не весь Забег. */
const KEEP = 32;

/** Потолок удержания Пробела/Enter, Кликов в секунду: уровень быстрого человека, а не автокликера. */
export const HOLD_CLICK_MAX_PER_SEC = 10;

/** Наименьшая пауза между Кликами удержания, мс: из потолка, а не наоборот. */
export const HOLD_CLICK_MIN_GAP_MS = 1000 / HOLD_CLICK_MAX_PER_SEC;

/**
 * Уровень Серии на момент `now` по моментам последних Кликов.
 *
 * Считаются только Клики окна: пока игрок молчит, они выходят из него один за другим, и уровень
 * спадает сам, без таймера. Момент из будущего (часы отвели назад) не считается — иначе Серия
 * застыла бы на высшем уровне до тех пор, пока часы не нагонят.
 */
export function streakLevel(moments: readonly number[], now: number): number {
  let inWindow = 0;
  for (const at of moments) {
    const age = now - at;
    if (age >= 0 && age < STREAK_WINDOW_MS) inWindow += 1;
  }
  let level = 0;
  for (let i = 1; i < STREAK_STEPS.length; i += 1) if (inWindow >= STREAK_STEPS[i]) level = i;
  return level;
}

/** Записывает Клик в `now` и возвращает моменты и уровень Серии, уже с ним. */
export function pushClick(
  moments: readonly number[],
  now: number,
): { moments: readonly number[]; level: number } {
  const next = [...moments.filter((at) => now - at < STREAK_WINDOW_MS && now - at >= 0), now].slice(-KEEP);
  return { moments: next, level: streakLevel(next, now) };
}

/**
 * Сколько кнопка Клика должна быть нажата мышью или пальцем, мс, чтобы это было удержание «Подумай
 * ещё», а не обычный Клик: короче — касание, и отпускание платит как всегда.
 */
export const POINTER_HOLD_ARM_MS = 350;

/** Сколько после отпускания удержания `click` ещё считается его концом, а не новым Кликом, мс. */
export const POINTER_HOLD_RELEASE_MS = 500;
